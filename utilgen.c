int32_t LSaltFromSz(char *psz) {
    int32_t lSalt;

    lSalt = 0;
    if (*psz == 0) {
        return 0;
    }
    while (*psz != 0) {
        lSalt += (int16_t)*psz;
        psz++;
        if (*psz != 0) {
            lSalt = (uint32_t)(lSalt * (int16_t)*psz);
            psz++;
        }
    }
    if (lSalt == 0) {
        lSalt = 1;
    }
    return lSalt;
}

