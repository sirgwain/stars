uint32_t GetDiskSerialNumber() {
    int16_t     j;
    int16_t     drive;
    char        fn[13];
    _find_t     fi;
    int16_t     i;
    int16_t     iWork;
    uint8_t     uDefault;
    uint16_t    uDate;
    int32_t     l;
    _diskfree_t df;

    iWork = 0;
    memset(vrgbEnvCur, 0, 11);
    CchGetString(idsC, fn);
    for (i = 0; i < 2; i++) {
        drive = i + 2;
        fn[0] = drive + 'A';
        l = 0;
        uDate = 0;
        if (GetDriveType(i + 2) != 3)
            goto NoDrive;
        if (dos_findfirst(fn, 8, &fi) == 0) {
            for (j = 0; j < 8 && fi.name[j] != 0; j++) {
                if (i == 0) {
                    l = (int32_t)(l << 4) | (int16_t)(fi.name[j] & 0xf);
                } else {
                    l = (int32_t)(l << 3) | (int16_t)(fi.name[j] & 7);
                }
            }
            if (i == 0) {
                uDate =
                    (fi.wr_date & 0xf) << 0xc | (fi.wr_date >> 5 & 7) << 9 | (fi.wr_time & 0xf) << 5 | (fi.wr_time >> 5 & 0xf) << 1 | (fi.wr_time >> 0xb & 1);
            } else {
                uDate = (fi.wr_date & 3) << 6 | (fi.wr_time & 7) << 3 | (fi.wr_time >> 5 & 7);
            }
        } else {
        NoDrive:
            uDate = 0xc57a;
            l = 1504107685;
        }
        vrgbEnvCur[iWork++] = l;
        vrgbEnvCur[iWork++] = l >> 8;
        vrgbEnvCur[iWork++] = HIWORD(l);
        if (i == 0) {
            vrgbEnvCur[iWork++] = l >> 0x18;
        }
        vrgbEnvCur[iWork++] = uDate;
        if (i == 0) {
            vrgbEnvCur[iWork++] = uDate >> 8;
        }
    }
    uDefault = 0;
    for (i = 0; i < 2; i++) {
        uDefault *= 16;
        if (GetDriveType(i + 2) != 3) {
            l = 1;
        } else {
            l = (uint32_t)dos_getdiskfree(i + 3, &df);
        }
        if (l == 0) {
            l = (int32_t)((uint32_t)df.total_clusters * (uint32_t)df.bytes_per_sector) / 0x200;
            l = (uint32_t)(l * (uint32_t)df.sectors_per_cluster);
            l = (int32_t)(l / 195312);
            if (l > 15) {
                l = 15;
            }
            uDefault += l & 0xf;
        }
    }
    vrgbEnvCur[iWork++] = uDefault;
    return iWork;
}

