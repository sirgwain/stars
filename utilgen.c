void Randomize(uint32_t dw) {
    int16_t a;
    int16_t b;

    a = LOWORD(dw) & 0x3f;
    b = LOWORD((uint32_t)(dw >> 6)) & 0x3f;
    if (a == b) {
        b = (b + 1) & 0x3f;
    }
    lRandSeed1 = rgPrimes[a];
    lRandSeed2 = rgPrimes[b];
    return;
}

