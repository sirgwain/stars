    s2 = lRandSeed2;
    k = (int32_t)(s1 / 53668);
    s1 = (uint32_t)((s1 - (uint32_t)(k * 53668)) * 0x9c4e) - (uint32_t)(k * 12211);
    if (s1 < 0) {
        s1 += 2147483563;
    }
    k = (int32_t)(s2 / 52774);
    s2 = (uint32_t)((s2 - (uint32_t)(k * 52774)) * 0x9ef4) - (uint32_t)(k * 3791);
    if (s2 < 0) {
        s2 += 2147483399;
    }
    z = s1 - s2;
    if (z < 1) {
        z += 2147483562;
    }
    lRandSeed1 = s1;
    lRandSeed2 = s2;
