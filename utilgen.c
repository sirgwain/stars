void BoundPoints(RECT *prc, POINT16 *rgpt, int16_t cpt) {
    int16_t ipt;
    int16_t xMax;
    int16_t yMax;
    int16_t xMin;
    int16_t yMin;

    xMax = rgpt->x;
    xMin = rgpt->x;
    yMax = rgpt->y;
    yMin = rgpt->y;
    for (ipt = 1; ipt < cpt; ipt++) {
        xMin = xMin >= rgpt[ipt].x ? rgpt[ipt].x : xMin;
        xMax = xMax <= rgpt[ipt].x ? rgpt[ipt].x : xMax;
        yMin = yMin >= rgpt[ipt].y ? rgpt[ipt].y : yMin;
        yMax = yMax <= rgpt[ipt].y ? rgpt[ipt].y : yMax;
    }
    prc->top = yMin - 1;
    prc->bottom = yMax + 1;
    prc->left = xMin - 1;
    prc->right = xMax + 1;
    return;
}

void StickyDlgPos(HWND hwnd, POINT16 *ppt, int16_t fInit) {
    POINT16 ptScreenMax;
    RECT    rc;

    GetWindowRect(hwnd, &rc);
    if (!fInit) {
        ppt->x = rc.left;
        ppt->y = rc.top;
    } else {
        ptScreenMax.x = GetSystemMetrics(SM_CXSCREEN);
        ptScreenMax.y = GetSystemMetrics(SM_CYSCREEN);
        if (ppt->x == -1 && ppt->y == -1) {
            rc.left = (ptScreenMax.x - (rc.right - rc.left)) >> 1;
            rc.top = (ptScreenMax.y - (rc.bottom - rc.top)) >> 1;
        } else {
            OffsetRect(&rc, ppt->x - rc.left, ppt->y - rc.top);
            if (rc.right > ptScreenMax.x) {
                rc.left += ptScreenMax.x - rc.right;
            }
            if (rc.bottom > ptScreenMax.y) {
                rc.top += ptScreenMax.y - rc.bottom;
            }
            if (rc.left < 0) {
                rc.left = 0;
            }
            if (rc.top < 0) {
                rc.top = 0;
            }
        }
        SetWindowPos(hwnd, NULL, rc.left, rc.top, 0, 0, SWP_NOSIZE | SWP_NOZORDER | SWP_NOACTIVATE);
    }
    return;
}

