HGLOBAL HdibLoadBigResource(BitmapId idb) {
    HRSRC   hrsrc;
    char   *lpstr;
    int16_t hfile;
    HGLOBAL hdib;

    hrsrc = FindResource(hInst, MAKEINTRESOURCE(idb), MAKEINTRESOURCE(2));
    if (hrsrc == 0) {
        return NULL;
    }
    hdib = AllocResource(hInst, hrsrc, 0);
    if (!hdib) {
        return NULL;
    }
    hfile = AccessResource(hInst, hrsrc);
    if (hfile == -1) {
    FreeAndFail:
        FreeResource(hdib);
        return NULL;
    }
    lpstr = LockResource(hdib);
    if (!lpstr) {
    CloseAndFail:
        _lclose(hfile);
        goto FreeAndFail;
    }
    if (ReadBigBlock(hfile, lpstr, SizeofResource(hInst, hrsrc)) == 0)
        goto CloseAndFail;
    _lclose(hfile);
    return hdib;
}

int16_t ReadBigBlock(int16_t hFile, char *lpBuffer, uint32_t dwSize) {
    int16_t nBytes;
    char   *lpInBuf;

    lpInBuf = lpBuffer;
    while (dwSize != 0) {
        nBytes = dwSize <= 30000 ? LOWORD(dwSize) : 30000;
        if (_lread(hFile, lpInBuf, nBytes) != nBytes) {
            return FALSE;
        }
        dwSize -= nBytes;
        lpInBuf += nBytes;
    }
    return TRUE;
}

int16_t FIntersectCircleLine(POINT16 ptL1, POINT16 ptL2, POINT16 ptC, int32_t r2, int16_t dMax, int16_t *pdStart, int16_t *pdEnd) {
    int32_t dyT;
    int32_t dxdy;
    int16_t dCtr;
    int32_t dy2;
    int32_t dy;
    int32_t yI;
    int32_t dyI;
    int32_t dxT;
    int32_t lT;
    int32_t dx2;
    int16_t dOff;
    int32_t dx;
    int32_t dxI;
    int32_t xI;
    int32_t r2I;

    dx = (int16_t)(ptL2.x - ptL1.x);
    dy = (int16_t)(ptL2.y - ptL1.y);
    dxdy = (uint32_t)(dx * dy);
    dx2 = (uint32_t)(dx * dx);
    dy2 = (uint32_t)(dy * dy);
    if (dxdy > 500000 || dx2 > 500000 || dy2 > 500000) {
        dxI = (double)(((long double)dxdy * (int16_t)(ptC.y - ptL1.y) + (long double)dx2 * ptC.x + (long double)dy2 * ptL1.x) / (dx2 + dy2));
        xI = (int32_t)dxI;
    } else {
        xI = (int32_t)((int32_t)((uint32_t)(dxdy * (int16_t)(ptC.y - ptL1.y)) + (uint32_t)(dx2 * ptC.x) + (uint32_t)(dy2 * ptL1.x)) / (dx2 + dy2));
    }
    if (dx != 0) {
        yI = ptL1.y + (int32_t)((int32_t)((xI - ptL1.x) * dy) / dx);
    } else {
        yI = ptL1.y;
    }
    dxI = xI - ptC.x;
    dyI = yI - ptC.y;
    r2I = (uint32_t)(dxI * dxI) + (uint32_t)(dyI * dyI);
    if (r2 <= r2I) {
        return FALSE;
    }
    dxT = xI - ptL1.x;
    dyT = yI - ptL1.y;
    lT = (uint32_t)(dxT * dxT) + (uint32_t)(dyT * dyT);
    dCtr = LOWORD((int32_t)sqrt((double)lT));
    lT = r2 - r2I;
    if (lT <= 0) {
        return FALSE;
    }
    dOff = LOWORD((int32_t)sqrt((double)lT));
    if (ptL1.x < ptL2.x) {
        if (xI < ptL1.x) {
            dCtr = -dCtr;
        }
    } else if (ptL1.x > ptL2.x) {
        if (xI > ptL1.x) {
            dCtr = -dCtr;
        }
    } else if (ptL1.y < ptL2.y) {
        if (yI < ptL1.y) {
            dCtr = -dCtr;
        }
    } else if (yI > ptL1.y) {
        dCtr = -dCtr;
    }
    *pdStart = 0 <= dCtr - dOff ? dCtr - dOff : 0;
    *pdEnd = dMax >= dCtr + dOff ? dCtr + dOff : dMax;
    if (*pdEnd <= 0 || *pdStart >= dMax) {
        return FALSE;
    }
    return TRUE;
}

void IntToRoman(int16_t i, char *pszOut) {
    if (i <= 0) {
        *pszOut = 0;
    } else {
        for (; i >= 10; i -= 10) {
            *pszOut++ = 'X';
        }
        if (i == 9) {
            *pszOut++ = 'I';
            *pszOut++ = 'X';
        } else {
            if (i >= 4) {
                if (i == 4) {
                    *pszOut++ = 'I';
                }
                *pszOut++ = 'V';
                i -= 5;
            }
            while (i-- > 0) {
                *pszOut++ = 'I';
            }
        }
        *pszOut = 0;
    }
    return;
}

