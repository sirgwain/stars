HBRUSH HbrGet(COLORREF cr) {
    int16_t iFree;
    int16_t i;
    HBRUSH  hbr;

    iFree = -1;
    for (i = 0; i < chbrCache; i++) {
        if (rghbrCacheUse[i] == 0) {
            iFree = i;
        } else if (rgcrCache[i] == cr) {
            rghbrCacheUse[i]++;
            return rghbrCache[i];
        }
    }
    hbr = CreateSolidBrush(cr);
    if (!hbr) {
        return NULL;
    }
    if (iFree == -1) {
        if (chbrCache >= 32) {
            return hbr;
        }
        iFree = chbrCache++;
    }
    rghbrCacheUse[iFree] = 1;
    rghbrCache[iFree] = hbr;
    rgcrCache[iFree] = cr;
    return hbr;
}

void FreeHbr(HBRUSH hbr) {
    int16_t i;

    for (i = 0; i < chbrCache; i++) {
        if (rghbrCacheUse[i] > 0 && hbr == rghbrCache[i]) {
            rghbrCacheUse[i]--;
            if (rghbrCacheUse[i] != 0) {
                return;
            }
        DeleteBrush:
            DeleteObject(hbr);
            return;
        }
    }
    goto DeleteBrush;
}

int16_t FCompressUserString(char *szIn, char *szOut, int16_t *pcOut) {
    int16_t fHalf;
    char    szWork[1024];
    int16_t iNyb;
    char   *pchOut;
    int16_t cNyb;

    fHalf = FALSE;
    pchOut = szWork;
    for (; *szIn != 0; szIn++) {
        iNyb = NybbleFromCh(*szIn);
        if (iNyb < 11) {
            cNyb = 1;
        } else if ((iNyb & 0xf) != 0xf) {
            cNyb = 2;
        } else {
            cNyb = 3;
        }
        while (cNyb-- != 0) {
            if (!fHalf) {
                *pchOut = (iNyb & 0xf) * 0x10;
                fHalf = TRUE;
            } else {
                *pchOut |= iNyb & 0xf;
                pchOut++;
                fHalf = FALSE;
                if (pchOut - szWork >= 0x400) {
                    return FALSE;
                }
            }
            iNyb >>= 4;
        }
    }
    if (fHalf) {
        *pchOut |= 0xf;
        pchOut++;
    }
    if (pchOut - szWork > *pcOut) {
        return FALSE;
    }
    *pcOut = pchOut - szWork;
    fmemcpy(szOut, szWork, *pcOut);
    return TRUE;
}

int16_t FDecompressUserString(char *szIn, int16_t cIn, char *szOut, int16_t *pcOut) {
    int16_t fHalf;
    char    szWork[1024];
    int16_t iNyb;
    char   *pchOut;

    fHalf = FALSE;
    pchOut = szWork;
    while (cIn > 0) {
        if (fHalf) {
            iNyb = *szIn & 0xf;
            cIn--;
            szIn++;
            if (iNyb == 15 && cIn == 0)
                break;
        } else {
            iNyb = *szIn >> 4 & 0xf;
        }
        fHalf = fHalf == 0;
        if (iNyb >= 11) {
            if (fHalf) {
                iNyb |= (*szIn & 0xf) << 4;
                cIn--;
                szIn++;
            } else {
                iNyb |= *szIn & 0xf0;
            }
            fHalf = fHalf == 0;
            if ((iNyb & 0xf) == 0xf) {
                if (fHalf) {
                    iNyb |= (*szIn & 0xf) << 8;
                    cIn--;
                    szIn++;
                } else {
                    iNyb |= (*szIn & 0xf0) << 4;
                }
                fHalf = fHalf == 0;
            }
        }
        *pchOut = ChFromNybble(iNyb);
        pchOut++;
        if (pchOut - szWork > *pcOut) {
            return FALSE;
        }
    }
    *pchOut = 0;
    fstrcpy(szOut, szWork);
    return TRUE;
}

int16_t NybbleFromCh(uint8_t ch) {
    char *pch;

    if (ch >= 97 && ch <= 122) {
        return rgcompstrlower[ch - 97];
    }
    if (ch == 32) {
        return 0;
    }
    if (ch >= 65 && ch <= 80) {
        return (ch - 0x41) << 4 | 0xb;
    }
    if (ch >= 81 && ch <= 90) {
        return (ch - 0x51) << 4 | 0xc;
    }
    if (ch >= 48 && ch <= 53) {
        return (ch - 0x26) << 4 | 0xc;
    }
    if (ch >= 54 && ch <= 57) {
        return (ch - 0x36) << 4 | 0xd;
    }
    pch = strchr(rgchcomp, ch);
    if (pch) {
        return (pch - rgchcomp + 4) << 4 | 0xe;
    }
    return ch << 4 | 0xf;
}

char ChFromNybble(int16_t nyb) {
    int16_t iPage;
    int16_t iVal;

    if (nyb < 11) {
        return rgchcompstrlower[nyb];
    }
    iPage = nyb & 0xf;
    if (iPage == 15) {
        return nyb >> 4;
    }
    iVal = (iPage - 0xb) * 0x10 + (nyb >> 4);
    if (iVal < 26) {
        return iVal + 65;
    }
    if (iVal < 36) {
        return iVal + 22;
    }
    if (iVal >= 52) {
        return rgchcomp[iVal - 52];
    }
    return rgchcompstrlower[iVal - 25];
}

